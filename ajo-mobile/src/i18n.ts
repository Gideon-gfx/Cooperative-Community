const DICTS: Record<Lang, Dict> = { EN: { ...EN, ...IGBA_EN }, PCM: { ...PCM, ...IGBA_PCM }, YO: { ...YO, ...IGBA_YO }, HA, IG };

export function translate(lang: Lang | undefined, key: string, vars: Record<string, string | number> = {}): string {
  const raw = DICTS[lang ?? 'EN']?.[key] ?? DICTS.EN[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
